"""Markdown report for a Security Brain run (downloadable, stored with the run)."""

from __future__ import annotations

from datetime import datetime
from typing import Any

from app.brain.agents import AGENTS, Finding
from app.brain.engine import ENGINE_VERSION
from app.brain.scoring import Score

SUBJECT_TITLE = {
    "alert": "Alert triage",
    "device": "Device risk assessment",
    "organization": "Organization posture",
}


def _cell(text: str) -> str:
    return " ".join(str(text).replace("|", "\\|").split())


def render(
    *,
    subject_type: str,
    subject_label: str,
    organization: str,
    generated_at: datetime,
    trigger: str,
    score: Score,
    summary: str,
    findings: list[Finding],
    recommendations: list[dict[str, Any]],
    trace: list[dict[str, Any]],
    agents: list[str],
) -> str:
    lines = [
        f"# {SUBJECT_TITLE[subject_type]}: {_cell(subject_label)}",
        "",
        f"- **Organization:** {_cell(organization)}",
        f"- **Generated:** {generated_at:%Y-%m-%d %H:%M:%S} UTC ({trigger})",
        f"- **Engine:** {ENGINE_VERSION} — deterministic rules, **no AI model**; every statement below is "
        "computed from your organization's own data.",
        "",
        "## Result",
        "",
        f"**Risk {score.score}/100 — {score.level.upper()}**"
        + (f" · priority **{score.priority}**" if subject_type == "alert" else "")
        + f" · data coverage {score.coverage}%",
        "",
        summary,
        "",
        "| Factor | Points | Evidence |",
        "|---|---:|---|",
    ]
    for f in score.factors:
        pts = f"{f['points']}/{f['max_points']}" if f["has_data"] else f"— /{f['max_points']} (no data)"
        lines.append(f"| {_cell(f['label'])} | {pts} | {_cell(f['evidence'])} |")
    if score.coverage < 100:
        lines += [
            "",
            f"> Coverage {score.coverage}%: factors without data score 0, so the risk score is a lower bound.",
        ]

    lines += ["", "## Recommendations", ""]
    if recommendations:
        for i, r in enumerate(recommendations, 1):
            flag = " *(changes a system — requires human approval)*" if r["changes_system"] else ""
            lines.append(f"{i}. **[{r['urgency']}]** {r['text']}{flag}")
        lines += ["", "_Recommendations only — nothing was executed._"]
    else:
        lines.append("No action recommended by the playbook.")

    lines += ["", "## Findings", ""]
    for name in agents:
        own = [f for f in findings if f.agent == name]
        lines += [f"### {AGENTS[name].title}", ""]
        if not own:
            lines += ["Nothing notable.", ""]
            continue
        for f in own:
            lines.append(
                f"- **{f.severity.upper()}** — {f.title}" + (f": {_cell(f.detail)}" if f.detail else "")
            )
        lines.append("")

    lines += ["## Tool calls (read-only)", "", "| # | Agent | Tool | Rows | ms |", "|---:|---|---|---:|---:|"]
    lines += [
        f"| {t['seq']} | {t['agent']} | `{t['tool']}` | {t['rows']} | {t['duration_ms']} |" for t in trace
    ]
    lines += [
        "",
        "---",
        "Generated by SENTINEL X Security Brain. Scores follow the published weights in the "
        "Security Brain page; verify findings before acting.",
        "",
    ]
    return "\n".join(lines)
